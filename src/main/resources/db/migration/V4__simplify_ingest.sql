CREATE TABLE ods_sensor_data_simple (
    record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_system VARCHAR(64) NOT NULL,
    source_record_id VARCHAR(128),
    sensor_code VARCHAR(128) NOT NULL,
    parameter_code VARCHAR(64) NOT NULL,
    collect_time TIMESTAMP WITH TIME ZONE NOT NULL,
    value_num DECIMAL(20,6),
    value_text VARCHAR(500),
    source_unit VARCHAR(32),
    quality_code VARCHAR(32),
    ingest_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK ((value_num IS NOT NULL AND value_text IS NULL) OR (value_num IS NULL AND value_text IS NOT NULL))
);

INSERT INTO ods_sensor_data_simple(source_system,source_record_id,sensor_code,parameter_code,collect_time,
 value_num,value_text,source_unit,quality_code,ingest_time,is_deleted)
