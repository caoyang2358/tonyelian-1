 value_num,source_unit,quality_code)
SELECT 'SEED_TREND','minute-seed-' || s.sensor_code || '-' || CAST(d.bucket_time AS VARCHAR),
 s.sensor_code,p.parameter_code,d.last_collect_time,d.last_value,d.unit_code,'GOOD'
