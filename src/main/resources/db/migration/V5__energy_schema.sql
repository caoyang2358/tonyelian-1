CREATE TABLE dim_energy_type (
    energy_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    energy_code VARCHAR(32) NOT NULL UNIQUE,
    energy_name VARCHAR(50) NOT NULL,
    standard_unit_code VARCHAR(32) NOT NULL REFERENCES dim_unit(unit_code),
    tce_factor DECIMAL(20,10) NOT NULL,
    factor_version VARCHAR(32) NOT NULL,
    effective_from DATE NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (energy_code IN ('ELECTRICITY','WATER','COAL_GAS')),
    CHECK (tce_factor >= 0)
);

