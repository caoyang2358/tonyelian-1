CREATE TABLE dim_energy_tariff (
    tariff_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    energy_type_id BIGINT NOT NULL REFERENCES dim_energy_type(energy_type_id),
    period_type VARCHAR(16) NOT NULL,
    start_minute INT NOT NULL,
    end_minute INT NOT NULL,
    unit_price DECIMAL(20,6) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    CHECK (period_type IN ('PEAK','FLAT','VALLEY','STANDARD')),
    CHECK (start_minute >= 0 AND start_minute < 1440),
    CHECK (end_minute > 0 AND end_minute <= 1440),
    CHECK (start_minute < end_minute),
    CHECK (unit_price >= 0)
);

CREATE TABLE dws_energy_hour (
    sensor_id BIGINT NOT NULL REFERENCES dim_sensor(sensor_id),
    bucket_time TIMESTAMP WITH TIME ZONE NOT NULL,
    consumption DECIMAL(20,6) NOT NULL,
    cost DECIMAL(20,6) NOT NULL DEFAULT 0,
    tce_amount DECIMAL(20,10) NOT NULL DEFAULT 0,
    peak_amount DECIMAL(20,6) NOT NULL DEFAULT 0,
    flat_amount DECIMAL(20,6) NOT NULL DEFAULT 0,
    valley_amount DECIMAL(20,6) NOT NULL DEFAULT 0,
    calculation_method VARCHAR(24) NOT NULL,
    quality_status VARCHAR(16) NOT NULL,
    factor_version VARCHAR(32) NOT NULL,
    refresh_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(sensor_id,bucket_time),
    CHECK (calculation_method IN ('CUMULATIVE_DIFF','INSTANT_INTEGRAL','NO_DATA')),
    CHECK (quality_status IN ('GOOD','PARTIAL','BAD','NO_DATA'))
);

CREATE TABLE dws_energy_day (
    sensor_id BIGINT NOT NULL REFERENCES dim_sensor(sensor_id),
    statistic_date DATE NOT NULL,
    consumption DECIMAL(20,6) NOT NULL,
    cost DECIMAL(20,6) NOT NULL DEFAULT 0,
    tce_amount DECIMAL(20,10) NOT NULL DEFAULT 0,
    peak_amount DECIMAL(20,6) NOT NULL DEFAULT 0,
    flat_amount DECIMAL(20,6) NOT NULL DEFAULT 0,
    valley_amount DECIMAL(20,6) NOT NULL DEFAULT 0,
    production_quantity DECIMAL(20,6),
    production_stage VARCHAR(32),
    quality_status VARCHAR(16) NOT NULL,
    factor_version VARCHAR(32) NOT NULL,
    refresh_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(sensor_id,statistic_date),
    CHECK (quality_status IN ('GOOD','PARTIAL','BAD','NO_DATA'))
);
