CREATE TABLE dim_workshop (
    workshop_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workshop_code VARCHAR(64) NOT NULL UNIQUE,
    workshop_name VARCHAR(100) NOT NULL,
    workshop_type VARCHAR(50), description VARCHAR(255), enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dim_equipment (
    equipment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_code VARCHAR(64) NOT NULL UNIQUE, equipment_name VARCHAR(100) NOT NULL,
    workshop_id BIGINT NOT NULL REFERENCES dim_workshop(workshop_id), responsible_person VARCHAR(100),
    enabled BOOLEAN NOT NULL DEFAULT TRUE, created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dim_unit (
    unit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_code VARCHAR(32) NOT NULL UNIQUE, unit_name VARCHAR(50) NOT NULL, unit_category VARCHAR(50) NOT NULL,
    base_unit_code VARCHAR(32), conversion_factor DECIMAL(20,10) NOT NULL DEFAULT 1,
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE dim_process (
    process_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_code VARCHAR(64) NOT NULL UNIQUE, process_name VARCHAR(100) NOT NULL,
    workshop_id BIGINT NOT NULL REFERENCES dim_workshop(workshop_id), sequence_no INT NOT NULL,
    description VARCHAR(255), enabled BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE(workshop_id, sequence_no)
);

CREATE TABLE dim_sensor (
    sensor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_code VARCHAR(128) NOT NULL UNIQUE, sensor_name VARCHAR(100) NOT NULL,
    equipment_id BIGINT NOT NULL REFERENCES dim_equipment(equipment_id), sensor_type VARCHAR(50), data_source VARCHAR(50),
    enabled BOOLEAN NOT NULL DEFAULT TRUE, created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dim_sensor_parameter (
    parameter_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id BIGINT NOT NULL REFERENCES dim_sensor(sensor_id), parameter_code VARCHAR(64) NOT NULL,
    parameter_name VARCHAR(100) NOT NULL, data_type VARCHAR(32) NOT NULL,
    unit_code VARCHAR(32) REFERENCES dim_unit(unit_code), decimal_places INT NOT NULL DEFAULT 2,
    normal_lower_limit DECIMAL(20,6), normal_upper_limit DECIMAL(20,6),
    alarm_lower_limit DECIMAL(20,6), alarm_upper_limit DECIMAL(20,6),
    sampling_frequency_seconds INT, enabled BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE(sensor_id, parameter_code),
    CHECK (data_type IN ('DECIMAL','INTEGER','BOOLEAN','STRING')),
    CHECK (sampling_frequency_seconds IS NULL OR sampling_frequency_seconds > 0)
);

CREATE TABLE dim_process_sensor_binding (
    binding_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_id BIGINT NOT NULL REFERENCES dim_process(process_id), sensor_id BIGINT NOT NULL REFERENCES dim_sensor(sensor_id),
    parameter_id BIGINT NOT NULL REFERENCES dim_sensor_parameter(parameter_id), display_role VARCHAR(16) NOT NULL,
    display_order INT NOT NULL DEFAULT 0, enabled BOOLEAN NOT NULL DEFAULT TRUE,
    primary_process_id BIGINT UNIQUE,
    created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(process_id, sensor_id, parameter_id, display_role),
    CHECK (display_role IN ('PRIMARY','TREND')),
    CHECK ((display_role='PRIMARY' AND enabled=TRUE AND primary_process_id=process_id) OR
           (NOT(display_role='PRIMARY' AND enabled=TRUE) AND primary_process_id IS NULL))
);

CREATE TABLE etl_ingest_batch (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_system VARCHAR(64) NOT NULL, received_count INT NOT NULL, success_count INT NOT NULL DEFAULT 0,
    failure_count INT NOT NULL DEFAULT 0, status VARCHAR(20) NOT NULL,
    started_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_time TIMESTAMP WITH TIME ZONE
);

CREATE TABLE etl_ingest_error (
    error_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES etl_ingest_batch(batch_id), item_index INT NOT NULL,
    source_record_id VARCHAR(128), error_code VARCHAR(64) NOT NULL, error_message VARCHAR(500) NOT NULL,
    created_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ods_sensor_data (
    record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_system VARCHAR(64) NOT NULL, source_record_id VARCHAR(128) NOT NULL,
    sensor_code VARCHAR(128) NOT NULL, parameter_code VARCHAR(64) NOT NULL,
    collect_time TIMESTAMP WITH TIME ZONE NOT NULL, value_num DECIMAL(20,6), value_text VARCHAR(500),
    source_unit VARCHAR(32), quality_code VARCHAR(32), ingest_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE(source_system, source_record_id),
    CHECK ((value_num IS NOT NULL AND value_text IS NULL) OR (value_num IS NULL AND value_text IS NOT NULL))
);
CREATE INDEX idx_ods_sensor_time ON ods_sensor_data(sensor_code, parameter_code, collect_time);

CREATE TABLE dws_sensor_parameter_minute (
    bucket_time TIMESTAMP WITH TIME ZONE NOT NULL, workshop_id BIGINT NOT NULL REFERENCES dim_workshop(workshop_id),
    equipment_id BIGINT NOT NULL REFERENCES dim_equipment(equipment_id), sensor_id BIGINT NOT NULL REFERENCES dim_sensor(sensor_id),
    parameter_id BIGINT NOT NULL REFERENCES dim_sensor_parameter(parameter_id), unit_code VARCHAR(32),
    reading_count BIGINT NOT NULL DEFAULT 0, avg_value DECIMAL(20,6), min_value DECIMAL(20,6),
    max_value DECIMAL(20,6), last_value DECIMAL(20,6), last_collect_time TIMESTAMP WITH TIME ZONE,
    abnormal_count BIGINT NOT NULL DEFAULT 0, refresh_time TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(bucket_time, sensor_id, parameter_id)
);

CREATE TABLE ads_parameter_monitor (
    sensor_id BIGINT NOT NULL REFERENCES dim_sensor(sensor_id), parameter_id BIGINT NOT NULL REFERENCES dim_sensor_parameter(parameter_id),
    workshop_id BIGINT NOT NULL REFERENCES dim_workshop(workshop_id), equipment_id BIGINT NOT NULL REFERENCES dim_equipment(equipment_id),
    unit_code VARCHAR(32), latest_value DECIMAL(20,6), latest_value_text VARCHAR(500),
    quality_status VARCHAR(16) NOT NULL, limit_status VARCHAR(16) NOT NULL,
    latest_collect_time TIMESTAMP WITH TIME ZONE NOT NULL, refresh_time TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(sensor_id, parameter_id),
    CHECK (quality_status IN ('GOOD','BAD','UNCERTAIN')),
    CHECK (limit_status IN ('NORMAL','WARNING','ALARM','UNKNOWN'))
);
